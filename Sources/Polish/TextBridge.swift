// MARK: - Synthetic keystrokes

enum KeySynth {
    /// Tag carried by every event we post, so our own event tap ignores it.
    static let marker: Int64 = 0x504F_4C49 // "POLI"

    static func press(_ key: Int, flags: CGEventFlags = []) {
        let src = CGEventSource(stateID: .privateState)
        for down in [true, false] {
            guard let ev = CGEvent(keyboardEventSource: src, virtualKey: CGKeyCode(key), keyDown: down) else { continue }
            ev.flags = flags
            ev.setIntegerValueField(.eventSourceUserData, value: marker)
            ev.post(tap: .cghidEventTap)
        }
    }

    static func selectAll() { press(kVK_ANSI_A, flags: .maskCommand) }
    static func copy() { press(kVK_ANSI_C, flags: .maskCommand) }
    static func paste() { press(kVK_ANSI_V, flags: .maskCommand) }
    static func moveRight() { press(kVK_RightArrow) }
}

func sleepMs(_ ms: UInt64) async {
    try? await Task.sleep(nanoseconds: ms * 1_000_000)
}

// MARK: - Pasteboard

struct PasteboardSnapshot {
    private let items: [[(NSPasteboard.PasteboardType, Data)]]

    init(_ pb: NSPasteboard = .general) {
        items = (pb.pasteboardItems ?? []).map { item in
            item.types.compactMap { t in item.data(forType: t).map { (t, $0) } }
        }
    }

    func restore(_ pb: NSPasteboard = .general) {
        pb.clearContents()
        guard !items.isEmpty else { return }
        let objs: [NSPasteboardItem] = items.map { pairs in
            let it = NSPasteboardItem()
            for (t, d) in pairs { it.setData(d, forType: t) }
            return it
        }
        pb.writeObjects(objs)
    }
}

enum Clipboard {
    /// Marks our temporary writes so clipboard managers skip them (nspasteboard.org convention).
    private static let transient = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
    private static let autoGenerated = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")

    static func setTemporary(_ s: String, _ pb: NSPasteboard = .general) {
        pb.clearContents()
        pb.declareTypes([.string, transient, autoGenerated], owner: nil)
        pb.setString(s, forType: .string)
        pb.setData(Data(), forType: transient)
        pb.setData(Data(), forType: autoGenerated)
    }

    /// Cmd+A, Cmd+C in the focused app and return the copied text, or nil if nothing was copied.
    static func copyAllText() async -> String? {
        let pb = NSPasteboard.general
        KeySynth.selectAll()
        await sleepMs(40)
        let before = pb.changeCount
        KeySynth.copy()
        for _ in 0..<30 {
            await sleepMs(20)
            if pb.changeCount != before { return pb.string(forType: .string) }
        }
        return nil
    }

    /// Replace the whole content of the focused field with `text`, keeping the user's clipboard intact.
    static func replaceAll(with text: String) async {
        let pb = NSPasteboard.general
        let snapshot = PasteboardSnapshot(pb)
        setTemporary(text, pb)
        KeySynth.selectAll()
        await sleepMs(40)
        KeySynth.paste()
        // Give the target app time to read the pasteboard before restoring it.
        await sleepMs(350)
        snapshot.restore(pb)
    }
}

// MARK: - Accessibility inspection

enum FocusKind {
    case text, nonText, unknown
}

enum FocusInspector {
    private static let textRoles: Set<String> = ["AXTextField", "AXTextArea", "AXComboBox", "AXSearchField"]
    /// Roles where Space has its own meaning (Quick Look, scrolling, toggling...).
    private static let nonTextRoles: Set<String> = [
        "AXList", "AXOutline", "AXTable", "AXBrowser", "AXButton", "AXCheckBox", "AXRadioButton",
        "AXSlider", "AXMenu", "AXMenuBar", "AXMenuItem", "AXImage", "AXWebArea", "AXScrollArea",
        "AXPopUpButton", "AXDisclosureTriangle", "AXCell", "AXRow", "AXTabGroup",
    ]

    static var isTrusted: Bool { AXIsProcessTrusted() }

    static func requestTrust() {
        let key = kAXTrustedCheckOptionPrompt.takeUnretainedValue() as String
        _ = AXIsProcessTrustedWithOptions([key: true] as CFDictionary)
    }

    static func focusedElement() -> AXUIElement? {
        let sys = AXUIElementCreateSystemWide()
        AXUIElementSetMessagingTimeout(sys, 0.25)
        var v: CFTypeRef?
        guard AXUIElementCopyAttributeValue(sys, kAXFocusedUIElementAttribute as CFString, &v) == .success,
              let v, CFGetTypeID(v) == AXUIElementGetTypeID() else { return nil }
        return (v as! AXUIElement)
    }

    static func string(_ el: AXUIElement, _ attr: String) -> String? {
        var v: CFTypeRef?
        guard AXUIElementCopyAttributeValue(el, attr as CFString, &v) == .success else { return nil }
        return v as? String
    }

    static func classify(_ el: AXUIElement?) -> FocusKind {
        guard let el, let role = string(el, kAXRoleAttribute) else { return .unknown }
        if textRoles.contains(role) { return .text }
        if let sub = string(el, kAXSubroleAttribute), textRoles.contains(sub) { return .text }
        var settable = DarwinBoolean(false)
        if AXUIElementIsAttributeSettable(el, kAXSelectedTextRangeAttribute as CFString, &settable) == .success,
           settable.boolValue {
            return .text
        }
        if nonTextRoles.contains(role) { return .nonText }
        return .unknown
    }

    /// Chromium/Electron only build their accessibility tree when asked; harmless elsewhere.
    static func enableManualAccessibility(pid: pid_t) {
        let app = AXUIElementCreateApplication(pid)
        AXUIElementSetMessagingTimeout(app, 0.25)
        AXUIElementSetAttributeValue(app, "AXManualAccessibility" as CFString, kCFBooleanTrue)
    }

    /// Screen rect (Cocoa coordinates) of the caret or focused element, for placing the HUD.
    static func anchorRect(_ el: AXUIElement?) -> NSRect? {
        guard let el else { return nil }
        var rect: CGRect?

        var rangeRef: CFTypeRef?
        if AXUIElementCopyAttributeValue(el, kAXSelectedTextRangeAttribute as CFString, &rangeRef) == .success,
           let rangeRef {
            var boundsRef: CFTypeRef?
            if AXUIElementCopyParameterizedAttributeValue(el, kAXBoundsForRangeParameterizedAttribute as CFString,
                                                          rangeRef, &boundsRef) == .success,
               let boundsRef, CFGetTypeID(boundsRef) == AXValueGetTypeID() {
                var r = CGRect.zero
                if AXValueGetValue(boundsRef as! AXValue, .cgRect, &r), r.width >= 0, r.height > 0 { rect = r }
            }
        }
        if rect == nil {
            var posRef: CFTypeRef?, sizeRef: CFTypeRef?
            if AXUIElementCopyAttributeValue(el, kAXPositionAttribute as CFString, &posRef) == .success,
               AXUIElementCopyAttributeValue(el, kAXSizeAttribute as CFString, &sizeRef) == .success,
               let posRef, let sizeRef {
                var p = CGPoint.zero, s = CGSize.zero
                AXValueGetValue(posRef as! AXValue, .cgPoint, &p)
                AXValueGetValue(sizeRef as! AXValue, .cgSize, &s)
                if s.width > 0 && s.height > 0 { rect = CGRect(origin: p, size: s) }
            }
        }
        guard let r = rect, let primary = NSScreen.screens.first else { return nil }
        // AX uses top-left origin on the primary screen; Cocoa uses bottom-left.
        return NSRect(x: r.minX, y: primary.frame.maxY - r.maxY, width: r.width, height: r.height)
    }
}
